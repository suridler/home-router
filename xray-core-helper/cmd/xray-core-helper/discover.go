package main

import (
	"context"
	"flag"
	"fmt"
	"io"
	"path/filepath"
	"strconv"
	"strings"
	"time"

	"home-router/xray-core-helper/internal/bootstrap"
	"home-router/xray-core-helper/internal/xrayservice"
)

func runDiscovery(args []string, configPath string, stdout, stderr io.Writer) int {
	flags := flag.NewFlagSet("discover-xray", flag.ContinueOnError)
	flags.SetOutput(stderr)
	dropIn := flags.Bool("systemd", false, "render helper path permissions using helper config")
	if flags.Parse(args) != nil || len(flags.Args()) != 0 {
		return 2
	}
	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()
	installation, err := xrayservice.New().Resolve(ctx)
	if err == nil {
		err = installation.CheckTrusted()
	}
	if err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	if !*dropIn {
		return writeJSONCode(stdout, installation)
	}
	config, err := bootstrap.Load(configPath)
	if err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	config.Xray.AssetDir = installation.AssetDir
	if _, err = config.GeodataAssetPath("geoip.dat"); err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	for _, dir := range []string{filepath.Dir(config.Storage.Database), filepath.Dir(config.Server.Socket)} {
		if err := xrayservice.TrustedPath(dir, false); err != nil {
			fmt.Fprintln(stderr, err)
			return 1
		}
	}
	text, err := pathDropIn(installation, config)
	if err != nil {
		fmt.Fprintln(stderr, err)
		return 1
	}
	fmt.Fprint(stdout, text)
	return 0
}

// pathDropIn renders only directories needed for atomic file replacement. It
// never resets administrator grants or expands permissions to filesystem roots.
func pathDropIn(installation xrayservice.Installation, config bootstrap.Config) (string, error) {
	dirs := []string{filepath.Dir(installation.Config), installation.AssetDir, filepath.Dir(config.Storage.Database), filepath.Dir(config.Server.Socket)}
	result := "# Generated by xray-core-helper installer; administrator drop-ins are preserved.\n[Service]\n"
	seen := map[string]bool{}
	for _, dir := range dirs {
		if !filepath.IsAbs(dir) || filepath.Clean(dir) != dir || strings.ContainsAny(dir, "\x00\r\n%") {
			return "", xrayservice.ErrInstallation
		}
		switch dir {
		case "/", "/etc", "/usr", "/usr/local", "/var", "/var/lib", "/run", "/opt", "/home", "/root":
			return "", xrayservice.ErrInstallation
		}
		if strings.HasPrefix(dir, "/home/") || strings.HasPrefix(dir, "/root/") || strings.HasPrefix(dir, "/proc/") || strings.HasPrefix(dir, "/sys/") || strings.HasPrefix(dir, "/dev/") || strings.HasPrefix(dir, "/tmp/") {
			return "", xrayservice.ErrInstallation
		}
		if !seen[dir] {
			result += "ReadWritePaths=" + strconv.Quote(dir) + "\n"
			seen[dir] = true
		}
	}
	return result, nil
}
